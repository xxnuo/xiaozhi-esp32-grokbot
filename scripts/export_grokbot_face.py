#!/usr/bin/env python3
"""Extract the sphere-face subset of the locally researched Grok Bot recipes.

The input belongs to the yin.wiki semantic reconstruction, not official engine
source. Geometry is independently rendered by main/display/grokbot_face.cc.
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "research/grokbot.yin.wiki/js/vendor/grok-recipes.json"
OUTPUT = ROOT / "main/display/grokbot_face_data.inc"
CLIPS = [
    "Idle_B", "Idle_D", "Idle_A", "Blocked_A", "Blocked_B", "Blocked_C",
    "Done_A", "Done_B", "Done_C", "Marketing_B", "Streaming_A", "Streaming_B",
    "Streaming_C", "Working_B",
]
TRACKS = ("position", "rotation", "squash", "scale", "lids", "expression")


def number(value):
    text = f"{value:.9g}"
    return text + ("f" if "." in text or "e" in text else ".0f")


def array(values):
    return "{" + ", ".join(number(value) for value in values) + "}"


def extract(recipes):
    lines = [
        "// Generated by uv run python scripts/export_grokbot_face.py.",
        "// Source: research/grokbot.yin.wiki/js/vendor/grok-recipes.json (semantic reconstruction).",
        "// This is a sphere-face subset, not official or complete Grok Bot engine source.",
    ]
    names = list(recipes["expressions"])
    lines.append("constexpr const char* kExpressionNames[] = {" + ", ".join(f'"{name}"' for name in names) + "};")
    lines.append("constexpr GrokBotFace::Eye kEyes[][2] = {")
    for name in names:
        lines.append("    { // " + name)
        for eye in recipes["expressions"][name]:
            fields = [array(eye["off"]), number(eye["tilt"]), number(eye["wid"]),
                      number(eye["lidY"]), array(eye["oval"]), array(eye["path"]),
                      number(1 if min(eye["oval"]) > 0 else 0)]
            lines.append("        {" + ", ".join(fields) + "},")
        lines.append("    },")
    lines += ["};", "constexpr float kBasis[2][3][3] = {"]
    for basis in recipes["eyes"]["basis"]:
        lines.append("    {" + ", ".join(array(basis[key]) for key in ("M", "C", "T")) + "},")
    lines.append("};")
    lines.append("constexpr float kAtlasStartRotation[] = " + array(recipes["eyes"]["baseEulerDeg"]) + ";")
    clips = {clip["name"]: clip for clip in recipes["clips"]}
    for name in CLIPS:
        for track in TRACKS:
            keys = clips[name]["tracks"].get(track, [])
            if not keys:
                continue
            kind = "ExpressionKey" if track == "expression" else "Key"
            lines.append(f"constexpr {kind} k{name}_{track}[] = {{")
            for key in keys:
                value = key["v"]
                if track == "expression":
                    index = -1 if value == "blink" else names.index(recipes["expressionAliases"].get(value, value))
                    fields = [number(key["t"]), str(index)]
                else:
                    fields = [number(key["t"]), array(value + [0] * (3 - len(value))), array(key["ease"])]
                lines.append("    {" + ", ".join(fields) + "},")
            lines.append("};")
    lines.append("constexpr Recipe kRecipes[] = {")
    for name in CLIPS:
        clip = clips[name]
        fields = [f'"{name}"', number(clip["duration"]), number(clip["squashAnchor"])]
        for track in TRACKS:
            keys = clip["tracks"].get(track, [])
            fields.extend([f"k{name}_{track}", str(len(keys))] if keys else ["nullptr", "0"])
        lines.append("    {" + ", ".join(fields) + "},")
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check checked-in constants without changing them")
    args = parser.parse_args()
    result = extract(json.loads(SOURCE.read_text()))
    if args.check:
        if OUTPUT.read_text() != result:
            parser.exit(1, "grokbot_face_data.inc is stale; rerun this exporter\n")
    else:
        OUTPUT.write_text(result)


if __name__ == "__main__":
    main()
